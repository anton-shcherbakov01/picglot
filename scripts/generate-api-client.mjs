#!/usr/bin/env node
/**
 * Writes `openapi.json` from the live FastAPI app and regenerates the small
 * typed surface the web app relies on, so a schema change is visible in a diff.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const isWindows = process.platform === 'win32';
const python = join(root, '.venv', isWindows ? 'Scripts/python.exe' : 'bin/python');

const outputDir = join(root, 'packages', 'api-client');
mkdirSync(outputDir, { recursive: true });
const specPath = join(outputDir, 'openapi.json');

execFileSync(python, ['-m', 'lingoimage.cli', 'openapi', '--output', specPath], {
  stdio: 'inherit',
  cwd: root,
});

const spec = JSON.parse(await import('node:fs').then((fs) => fs.readFileSync(specPath, 'utf8')));

const operations = [];
for (const [path, methods] of Object.entries(spec.paths ?? {})) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!operation.operationId) continue;
    operations.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      summary: operation.summary ?? '',
    });
  }
}

const banner = '// Generated by scripts/generate-api-client.mjs — do not edit by hand.\n';
writeFileSync(
  join(outputDir, 'operations.ts'),
  `${banner}
export interface ApiOperation {
  readonly id: string;
  readonly method: string;
  readonly path: string;
  readonly summary: string;
}

export const OPERATIONS = ${JSON.stringify(operations, null, 2)} as const satisfies readonly ApiOperation[];

export const ERROR_CODES = ${JSON.stringify(
    Object.keys(spec.components?.schemas ?? {}).includes('ErrorBody')
      ? 'see docs/api/public-api.md'
      : '',
  )};
`,
);

console.log(`Wrote ${operations.length} operations to packages/api-client/`);
